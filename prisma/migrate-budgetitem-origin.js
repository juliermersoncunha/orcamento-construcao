// Adds origin metadata columns to BudgetItem so fixture-generated items carry
// their room, source equipment and memory-of-calc. All nullable — existing rows
// and the classic per-phase calculation stay untouched.
//
// Usage:
//   node prisma/migrate-budgetitem-origin.js
//   node prisma/migrate-budgetitem-origin.js "<conn-string>"
require("dotenv").config();
const { Client } = require("pg");

const connectionString = process.argv[2] || process.env.DIRECT_DATABASE_URL;

async function main() {
  if (!connectionString) throw new Error("No connection string (arg or DIRECT_DATABASE_URL)");
  const needsSsl = /supabase\.(com|co)/.test(connectionString);
  const client = new Client({
    connectionString,
    ...(needsSsl ? { ssl: { rejectUnauthorized: false } } : {}),
  });
  await client.connect();
  console.log("Connected to database");

  const cols = [
    `ADD COLUMN IF NOT EXISTS "roomId" TEXT`,
    `ADD COLUMN IF NOT EXISTS "sourceKind" TEXT`,
    `ADD COLUMN IF NOT EXISTS "sourceLabel" TEXT`,
    `ADD COLUMN IF NOT EXISTS "formula" TEXT`,
    `ADD COLUMN IF NOT EXISTS "autoGenerated" BOOLEAN NOT NULL DEFAULT true`,
  ];
  for (const c of cols) {
    await client.query(`ALTER TABLE "BudgetItem" ${c}`);
    console.log(`  BudgetItem ${c}`);
  }

  const { rows } = await client.query(
    `SELECT column_name FROM information_schema.columns
      WHERE table_name = 'BudgetItem' AND column_name IN ('roomId','sourceKind','sourceLabel','formula','autoGenerated')
      ORDER BY column_name`
  );
  console.log("\nVerify:", rows.map((r) => r.column_name).join(", "));

  await client.end();
  console.log("Done.");
}

main().catch((e) => { console.error(e); process.exit(1); });
