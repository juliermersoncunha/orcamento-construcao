"use server";

import { revalidatePath } from "next/cache";
import { redirect } from "next/navigation";
import { prisma } from "@/lib/prisma";
import { getSession } from "@/lib/session";
import { PhaseType } from "@prisma/client";

async function assertOwnsProject(projectId: string) {
  const session = await getSession();
  if (!session) redirect("/login");
  const p = await prisma.project.findFirst({
    where: { id: projectId, userId: session.userId },
    select: { id: true },
  });
  if (!p) redirect("/projetos");
  return p;
}

// A linha da tela do orçamento é "fase:materialId".
function chave(linha: string) {
  const [phase, materialId] = linha.split(":");
  if (!materialId || !(Object.values(PhaseType) as string[]).includes(phase)) return null;
  return { phase: phase as PhaseType, materialId };
}

function revalidar(projectId: string) {
  revalidatePath(`/projetos/${projectId}/orcamento`);
  revalidatePath(`/projetos/${projectId}/wizard`);
}

// Tira do orçamento a parte calculada de uma linha, para o usuário lançar à
// mão na Etapa 8. O que foi lançado à mão no mesmo material fica.
export async function substituirPorManual(projectId: string, linha: string) {
  await assertOwnsProject(projectId);
  const k = chave(linha);
  if (!k) return { error: "Linha inválida." };

  const auto = await prisma.budgetItem.findMany({
    where: { projectId, ...k, autoGenerated: true },
    select: { id: true, quantity: true },
  });
  if (auto.length === 0) return { error: "Este item não tem parte calculada." };

  await prisma.$transaction([
    prisma.excludedBudgetItem.upsert({
      where: { projectId_phase_materialId: { projectId, ...k } },
      create: { projectId, ...k, calcQuantity: auto.reduce((s, i) => s + i.quantity, 0) },
      update: { calcQuantity: auto.reduce((s, i) => s + i.quantity, 0) },
    }),
    prisma.budgetItem.deleteMany({ where: { id: { in: auto.map((i) => i.id) } } }),
  ]);
  revalidar(projectId);
  return {};
}

// Desfaz a substituição: o item calculado volta com a quantidade do último
// cálculo e o preço atual do catálogo.
export async function voltarAoCalculado(projectId: string, linha: string) {
  await assertOwnsProject(projectId);
  const k = chave(linha);
  if (!k) return { error: "Linha inválida." };

  const ex = await prisma.excludedBudgetItem.findUnique({
    where: { projectId_phase_materialId: { projectId, ...k } },
    include: { material: { select: { currentPrice: true } } },
  });
  if (!ex) return {};

  await prisma.$transaction([
    prisma.excludedBudgetItem.delete({ where: { id: ex.id } }),
    ...(ex.calcQuantity > 0
      ? [prisma.budgetItem.create({
          data: {
            projectId, ...k,
            quantity: ex.calcQuantity,
            unitPriceSnapshot: ex.material.currentPrice,
            sourceKind: "GENERIC",
            autoGenerated: true,
          },
        })]
      : []),
  ]);
  revalidar(projectId);
  return {};
}
